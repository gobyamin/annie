/* ============================================================
   학생이 배운 글자만 남기기

   왜: 애니는 2회차에 모음 다섯 개를 배운다. 그런데 01d 는 21개를 다 보여준다.
   왕초보에게 안 배운 열여섯 개를 같이 들이미는 건 도움이 아니라 방해다.

   팩에 이렇게 적으면 그 글자만 남는다. 안 적으면 전부 나온다(지금까지와 같음).

     "letters": {
       "vowels":     ["ㅏ","ㅔ","ㅣ","ㅗ","ㅜ"],
       "consonants": ["ㄴ","ㅇ"]
     }

   실제 한글 낱자를 적는다. 내부 id(a, eo, sound-g)가 아니라
   선생님이 진도표에 쓰는 그대로여야 헷갈리지 않는다.

   비면 빈 채로 돌려준다. 합성모음처럼 "정당하게 0개" 인 경우가 있어서,
   여기서 되살리면 안 배운 글자가 9개나 딸려 들어온다.
   전부 비어서 앱이 껍데기가 되는 것은 **앱 쪽에서** 막는다.
   ============================================================ */

function ONLY(list, kind) {
  try {
    var P = window.STUDENT_PACK;
    var want = P && P.letters && P.letters[kind];
    if (!want || !want.length) return list;
    return list.filter(function (x) { return want.indexOf(x.c) >= 0; });
  } catch (e) { return list; }
}
